#!/usr/bin/env node
/**
 * Generates `typecheck/tsconfig.json` by reading every `registry/<cat>/registry.json`
 * and mapping each item's install `target` back to its source file.
 *
 * Why generated rather than hand-written: primitives import each other by their
 * INSTALLED path (`@/lib/db`, `@/hooks/use-debounce`), not their repo path
 * (`registry/utilities/db.ts`). A hand-maintained map would rot the moment
 * someone adds a primitive — which is precisely the class of drift this harness
 * exists to catch.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const repoRoot = path.resolve(root, "..");
const registryDir = path.join(repoRoot, "registry");

const paths = {};
let fileCount = 0;
const collisions = [];

for (const cat of fs.readdirSync(registryDir)) {
  const registryJson = path.join(registryDir, cat, "registry.json");
  if (!fs.existsSync(registryJson)) continue;

  const { items } = JSON.parse(fs.readFileSync(registryJson, "utf8"));

  for (const item of items) {
    for (const file of item.files) {
      if (!file.target) continue;

      // "~/lib/db.ts" -> alias "@/lib/db", source "registry/utilities/db.ts"
      const alias = "@" + file.target.slice(1).replace(/\.(tsx?|jsx?)$/, "");
      const source = `../registry/${cat}/${file.path}`;

      if (paths[alias] && paths[alias][0] !== source) {
        collisions.push(`${alias}: ${paths[alias][0]} vs ${source}`);
      }
      paths[alias] = [source];
      fileCount++;
    }
  }
}

if (collisions.length > 0) {
  console.error(`\n✖ Two primitives claim the same install path:`);
  for (const c of collisions) console.error(`    - ${c}`);
  console.error(`\nOne would overwrite the other on install. Fix the targets.`);
  process.exit(1);
}

/**
 * A `paths` entry bypasses TypeScript's automatic `@types/<pkg>` lookup, so a
 * bare `react` would resolve to untyped JS and every JSX element would error
 * with "no interface JSX.IntrinsicElements". Map any package that has a
 * companion @types package at its declarations explicitly.
 */
function typesAliases() {
  const typesDir = path.join(root, "node_modules", "@types");
  const out = {};
  if (!fs.existsSync(typesDir)) return out;

  for (const entry of fs.readdirSync(typesDir)) {
    if (entry.startsWith(".")) continue;
    // `@types/tanstack__react-query` provides types for `@tanstack/react-query`.
    const pkg = entry.includes("__") ? "@" + entry.replace("__", "/") : entry;
    out[pkg] = [`./node_modules/@types/${entry}`, `./node_modules/${pkg}`];
  }
  return out;
}

// Shims come last so a real primitive always wins over a stub. `@/lib/utils`
// (shadcn's cn) and `@/components/ui/*` are provided by shadcn init in a real
// project, not by this repo — see shims/.
const tsconfig = {
  "//": "GENERATED by scripts/gen-tsconfig.mjs — do not edit by hand.",
  compilerOptions: {
    target: "ES2022",
    lib: ["dom", "dom.iterable", "ES2022"],
    jsx: "preserve",
    module: "esnext",
    moduleResolution: "bundler",
    allowJs: true,
    esModuleInterop: true,
    resolveJsonModule: true,
    isolatedModules: true,
    strict: true,
    noEmit: true,
    skipLibCheck: true,
    forceConsistentCasingInFileNames: true,
    baseUrl: ".",
    // The sources being compiled live in ../registry, so TypeScript would walk
    // UP from there looking for node_modules and never find the deps installed
    // here. The trailing "*" entry points bare specifiers (react, zod, next/…)
    // at this package's node_modules. It is last because TS prefers the longest
    // matching pattern, so the "@/…" aliases above always win.
    paths: {
      ...paths,
      "@/components/ui/*": ["./shims/shadcn-ui.ts"],
      "@/lib/utils": ["./shims/shadcn-utils.ts"],
      ...typesAliases(),
      "*": ["./node_modules/*"],
    },
    typeRoots: ["./node_modules/@types"],
  },
  include: ["../registry/**/*.ts", "../registry/**/*.tsx", "shims/**/*.ts", "shims/**/*.d.ts"],
};

const out = path.join(root, "tsconfig.json");
fs.writeFileSync(out, JSON.stringify(tsconfig, null, 2) + "\n", "utf8");

console.log(`  ✓ mapped ${fileCount} files → ${Object.keys(paths).length} aliases`);
console.log(`Wrote ${path.relative(repoRoot, out)}`);
